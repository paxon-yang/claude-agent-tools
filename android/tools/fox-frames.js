#!/usr/bin/env node
// 把"小狐狸"皮肤那一幕截成安卓卡片用的逐帧图片（16 帧 × 150 毫秒），浅色和深色各一套，带一点投影。
// 改了 agent-viz/public/skins.js 里的 foxScene() 之后跑一次：node android/tools/fox-frames.js
// Cuts the Fox skin's scene into frames for the Android card (16 × 150 ms), light and dark, with a soft shadow.
// Run after changing foxScene() in agent-viz/public/skins.js: node android/tools/fox-frames.js
'use strict';
const path = require('path');
const fs = require('fs');
let chromium;
try { ({ chromium } = require('playwright')); } catch { ({ chromium } = require('/opt/npm-tools/node_modules/playwright')); }
const Skins = require('../../agent-viz/public/skins.js');

const DP = 3, H_DP = 92, PAD_DP = 6;            // 卡片上的高度 92dp，四周留 6dp 给投影 / 92 dp tall on the card, 6 dp around for the shadow
const RES = path.join(__dirname, '..', 'app', 'src', 'main', 'res');

(async () => {
  const v = Skins.foxView(false);
  const W_DP = Math.round(H_DP * v.w / v.h);
  const W = (W_DP + 2 * PAD_DP) * DP, H = (H_DP + 2 * PAD_DP) * DP;
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  for (const dark of [false, true]) {
    const dir = path.join(RES, dark ? 'drawable-night-nodpi' : 'drawable-nodpi');
    fs.mkdirSync(dir, { recursive: true });
    for (let i = 0; i < Skins.FOX_FRAMES; i++) {
      await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent"><div style="padding:${PAD_DP * DP}px;width:${W_DP * DP}px;height:${H_DP * DP}px;filter:drop-shadow(0 ${4 * DP}px ${3 * DP}px rgba(0,0,0,${dark ? 0.35 : 0.12}))">${Skins.foxSvg(dark, i / Skins.FOX_FRAMES)}</div></body></html>`);
      await page.screenshot({ path: path.join(dir, `fox_f${i}.png`), omitBackground: true, clip: { x: 0, y: 0, width: W, height: H } });
    }
    console.log('wrote', dir);
  }
  const items = Array.from({ length: Skins.FOX_FRAMES }, (_, i) => `    <item android:drawable="@drawable/fox_f${i}" android:duration="${Skins.FOX_STEP}" />`).join('\n');
  fs.writeFileSync(path.join(RES, 'drawable', 'fox_anim.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- 由 android/tools/fox-frames.js 生成 / generated by android/tools/fox-frames.js -->
<animation-list xmlns:android="http://schemas.android.com/apk/res/android" android:oneshot="false">
${items}
</animation-list>
`);
  fs.writeFileSync(path.join(RES, 'values', 'fox_dimens.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- 由 android/tools/fox-frames.js 生成：小狐狸那一层的大小（含投影留白）/ generated: size of the fox layer, shadow margin included -->
<resources>
    <dimen name="fox_w">${W_DP + 2 * PAD_DP}dp</dimen>
    <dimen name="fox_h">${H_DP + 2 * PAD_DP}dp</dimen>
    <dimen name="fox_pad">${PAD_DP}dp</dimen>
</resources>
`);
  await browser.close();
  // 有 Python + Pillow 就压成 256 色，APK 小很多 / with Python + Pillow, quantise to 256 colours for a smaller APK
  const py = `from PIL import Image\nimport glob\nfor f in glob.glob(${JSON.stringify(path.join(RES, 'drawable*-nodpi', 'fox_f*.png'))}):\n    im=Image.open(f).convert('RGBA')\n    im.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(f, optimize=True)\n`;
  const r = require('child_process').spawnSync('python3', ['-c', py], { stdio: 'inherit' });
  console.log(r.status === 0 ? 'quantised' : 'left as full-colour PNGs (no python3/Pillow)');
})();
