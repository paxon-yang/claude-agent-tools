#!/usr/bin/env node
// 把"工位"皮肤那一幕截成安卓卡片用的逐帧图片（16 帧 × 150 毫秒 = 2.4 秒一圈），浅色和深色各一套。
// 改了 agent-viz/public/skins.js 里的 scene() 之后跑一次：node android/tools/desk-frames.js
// Cuts the Desk skin's scene into frames for the Android card (16 × 150 ms = one 2.4 s loop), light and dark.
// Run after changing scene() in agent-viz/public/skins.js: node android/tools/desk-frames.js
'use strict';
const path = require('path');
const fs = require('fs');
let chromium;
try { ({ chromium } = require('playwright')); } catch { ({ chromium } = require('/opt/npm-tools/node_modules/playwright')); }
const Skins = require('../../agent-viz/public/skins.js');

const FRAMES = 16, STEP = 150, W = 450, H = 338, OPACITY = 0.85;
const RES = path.join(__dirname, '..', 'app', 'src', 'main', 'res');

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  for (const dark of [false, true]) {
    const dir = path.join(RES, dark ? 'drawable-night-nodpi' : 'drawable-nodpi');
    fs.mkdirSync(dir, { recursive: true });
    await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent"><style>.ds .gl{display:none}</style><div style="width:${W}px;height:${H}px;opacity:${OPACITY}">${Skins.scene(dark)}</div></body></html>`);
    await page.waitForTimeout(200);
    for (let i = 0; i < FRAMES; i++) {
      await page.evaluate(ms => document.getAnimations().forEach(a => { a.pause(); a.currentTime = ms; }), i * STEP);
      await page.screenshot({ path: path.join(dir, `desk_f${i}.png`), omitBackground: true, clip: { x: 0, y: 0, width: W, height: H } });
    }
    console.log('wrote', dir);
  }
  // 逐帧动画 / the frame animation
  const items = Array.from({ length: FRAMES }, (_, i) => `    <item android:drawable="@drawable/desk_f${i}" android:duration="${STEP}" />`).join('\n');
  fs.writeFileSync(path.join(RES, 'drawable', 'desk_anim.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- 由 android/tools/desk-frames.js 生成 / generated by android/tools/desk-frames.js -->
<animation-list xmlns:android="http://schemas.android.com/apk/res/android" android:oneshot="false">
${items}
</animation-list>
`);
  await browser.close();
  // 有 Python + Pillow 就把图片压成 200 色，APK 小很多（光晕在卡片底图里画，这里不画，免得压出色带）
  // with Python + Pillow, quantise to 200 colours for a much smaller APK (the glow lives in the card's base layer, so no banding)
  const py = `from PIL import Image\nimport glob\nfor f in glob.glob(${JSON.stringify(path.join(RES, 'drawable*-nodpi', 'desk_f*.png'))}):\n    im=Image.open(f).convert('RGBA')\n    im.quantize(colors=200, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(f, optimize=True)\n`;
  const r = require('child_process').spawnSync('python3', ['-c', py], { stdio: 'inherit' });
  console.log(r.status === 0 ? 'quantised' : 'left as full-colour PNGs (no python3/Pillow)');
})();
